"""Build the federated patient-level DP grid from finished lr-selection runs (D33).

Pre-registered rule: a unit-level run uses the learning rate selected at seed 0
for the record-level run with the same scenario and target epsilon. Only
scenarios where no patient is split across clients are used, because a patient
held by m clients is released by m mechanisms and its guarantee composes.

    python scripts/make_unit_grid.py --runs results/runs \
        --grids configs/grids/week03_select_fed.yaml configs/grids/week04_select_udir.yaml \
        --scenarios natural3 udir0.5_k10 --epsilons 8 3 \
        --out configs/grids/week04_unit_fed.yaml
"""
from __future__ import annotations

import argparse
import copy
import os
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from scripts.select_lr import select  # noqa: E402
from src.run import resolve  # noqa: E402


def unit_presets(grids: list[dict], runs_dir: str, scenarios: list[str], epsilons: list[float]) -> list[dict]:
    out = []
    for g in grids:
        presets, _ = select(g, runs_dir)
        for p in presets:
            r = resolve(p)
            if (r["dp"]["enabled"] and r["data"]["scenario"] in scenarios
                    and r["dp"]["target_epsilon"] in epsilons and r["dp"].get("noise_multiplier") is None):
                q = copy.deepcopy(p)
                q.setdefault("dp", {})["unit"] = "unit"
                q.setdefault("train", {}).pop("seed", None)
                if not q["train"]:
                    q.pop("train")
                out.append(q)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default="results/runs")
    ap.add_argument("--grids", nargs="+", required=True)
    ap.add_argument("--scenarios", nargs="+", default=["natural3", "udir0.5_k10"])
    ap.add_argument("--epsilons", type=float, nargs="+", default=[8.0, 3.0])
    ap.add_argument("--seeds", type=int, nargs="+", default=[1, 2, 3, 4, 5])
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    presets = unit_presets([yaml.safe_load(open(g)) for g in a.grids], a.runs, a.scenarios, a.epsilons)
    grid = {"name": os.path.splitext(os.path.basename(a.out))[0],
            "note": "Generated by scripts/make_unit_grid.py. Unit-level DP, lr taken from the "
                    "record-level selection at the same scenario and epsilon (D33).",
            "presets": presets, "axes": {"train.seed": a.seeds}}
    yaml.safe_dump(grid, open(a.out, "w"), sort_keys=False)
    for p in presets:
        print(p)
    print(f"{len(presets)} configurations x {len(a.seeds)} seeds -> {a.out}")


if __name__ == "__main__":
    main()
