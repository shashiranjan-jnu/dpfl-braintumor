"""Learning-rate selection protocol (decision D30).

Phase 1 runs every configuration of a selection grid at seed 0 with each
candidate learning rate. For each configuration, ignoring the learning rate,
this script picks the learning rate with the lowest best validation loss and
writes a follow-up grid that reruns exactly those configurations at the
reporting seeds. Seed 0 is used for selection only and is never reported.

    python scripts/select_lr.py --grid configs/grids/week03_select_fed.yaml \
        --runs results/runs --seeds 1 2 3 4 5 \
        --out configs/grids/week03_fed_seeds.yaml --table results/tables/week03_lr_selection.csv
"""
from __future__ import annotations

import argparse
import copy
import json
import os
import sys

import pandas as pd
import yaml

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from scripts.run_grid import expand  # noqa: E402
from src.run import resolve, run_id  # noqa: E402


def select(grid: dict, runs_dir: str, param: str = "optim.lr") -> tuple[list[dict], pd.DataFrame]:
    """Pick, per configuration, the value of `param` (dotted key) with the lowest best validation loss."""
    sect, key = param.split(".")
    rows, missing = [], []
    for cfg in expand(grid):
        rid = run_id(resolve(cfg))
        path = os.path.join(runs_dir, rid, "metrics.json")
        if not os.path.exists(path):
            missing.append(rid)
            continue
        m = json.load(open(path))
        key_cfg = copy.deepcopy(cfg)
        lr = key_cfg.get(sect, {}).pop(key)
        if key_cfg.get(sect) == {}:
            key_cfg.pop(sect)
        rows.append({"key": json.dumps(key_cfg, sort_keys=True), "lr": lr, "run_id": rid,
                     "best_val_loss": min(h["val_loss"] for h in m["history"]),
                     "diverged": m.get("diverged", False),
                     "val_bal_acc_at_best": next(h["val_bal_acc"] for h in m["history"]
                                                 if h["round"] == m["best_round"]) if m["best_round"] > 0 else None})
    if missing:
        raise SystemExit(f"{len(missing)} selection runs missing, e.g. {missing[:3]}")
    df = pd.DataFrame(rows)
    df.loc[df.diverged, "best_val_loss"] = float("inf")
    winners = df.loc[df.groupby("key").best_val_loss.idxmin()]
    df["selected"] = df.run_id.isin(winners.run_id)
    presets = []
    for _, w in winners.iterrows():
        cfg = json.loads(w.key)
        cfg.setdefault(sect, {})[key] = w.lr
        cfg.get("train", {}).pop("seed", None)      # the follow-up grid sets the reporting seeds
        if cfg.get("train") == {}:
            cfg.pop("train")
        presets.append(cfg)
    return presets, df.drop(columns="key")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--grid", required=True)
    ap.add_argument("--runs", default="results/runs")
    ap.add_argument("--seeds", type=int, nargs="+", default=[1, 2, 3, 4, 5])
    ap.add_argument("--out", required=True)
    ap.add_argument("--table", default=None)
    ap.add_argument("--param", default="optim.lr", help="dotted key to select, e.g. fl.mu")
    a = ap.parse_args()
    grid = yaml.safe_load(open(a.grid))
    presets, table = select(grid, a.runs, a.param)
    follow = {"name": os.path.splitext(os.path.basename(a.out))[0],
              "note": f"Generated by scripts/select_lr.py from {os.path.basename(a.grid)}. "
                      f"{a.param} fixed per configuration by lowest validation loss at seed 0.",
              "presets": presets, "axes": {"train.seed": a.seeds}}
    yaml.safe_dump(follow, open(a.out, "w"), sort_keys=False)
    if a.table:
        os.makedirs(os.path.dirname(a.table), exist_ok=True)
        table.to_csv(a.table, index=False)
    print(table.to_string(index=False))
    print(f"\n{len(presets)} configurations x {len(a.seeds)} seeds -> {a.out}")


if __name__ == "__main__":
    main()
