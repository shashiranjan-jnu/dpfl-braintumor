"""Grids for the LiRA shadow models and the weight-noise comparator (Step 4.1, D45).

    python scripts/make_shadow_grid.py lira            # writes configs/grids/week07_lira_shadows.yaml
    python scripts/make_shadow_grid.py wn --results RES  # after week07_wn_select has run

Shadow model s of a target configuration copies that configuration, trains on
the units kept by data.shadow.seed = s (half of train plus test, whole patients)
and uses train.seed 1000 + s. DP shadows fix dp.noise_multiplier to the
target's calibrated sigma, so they run the identical mechanism on a smaller pool.

The weight-noise comparator keeps Gupta et al.'s literal sigma 0.5 and adds one
utility-matched sigma, fixed by a rule written before the selection runs: the
largest sigma in week07_wn_select whose seed-0 best validation loss is at most
that of record-level epsilon 8 FedAvg on natural3 at seed 0 (run 7ee9f745d947,
0.656). If none qualifies, the smallest sigma is used.
"""
from __future__ import annotations

import argparse
import copy
import json
import os
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from src.run import deep_update, resolve, run_id  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
N_SHADOW = 16
NAT3 = {"data": {"scenario": "natural3"}}
# The four natural3 FedAvg targets of week03_fed_seeds_a/b (lr from week03_lr_selection).
LIRA_TARGETS = [
    deep_update(NAT3, {"optim": {"lr": 0.01}}),
    deep_update(NAT3, {"dp": {"enabled": True, "target_epsilon": 8.0}, "optim": {"lr": 0.01}}),
    deep_update(NAT3, {"dp": {"enabled": True, "target_epsilon": 3.0}, "optim": {"lr": 0.003}}),
    deep_update(NAT3, {"dp": {"enabled": True, "target_epsilon": 1.0}, "optim": {"lr": 0.003}}),
]
WN_SIGMAS = [0.5, 0.05, 0.01, 0.003, 0.001]
WN_LITERAL = 0.5
REF_EPS8_SEED0 = "7ee9f745d947"


def sigma_of(target: dict, results: str) -> float:
    rid = run_id(resolve(deep_update(target, {"train": {"seed": 1}})))
    return float(json.load(open(os.path.join(results, "runs", rid, "metrics.json")))["privacy"]["sigma"])


def shadow_presets(targets: list[dict], results: str) -> list[dict]:
    out = []
    for t in targets:
        t = copy.deepcopy(t)
        if t.get("dp", {}).get("enabled"):
            t["dp"]["noise_multiplier"] = sigma_of(t, results)
        out.append(t)
    return out


def shadow_grid(name: str, presets: list[dict], note: str) -> dict:
    seeds = list(range(N_SHADOW))
    return {"name": name, "note": note,
            "fixed": {"data": {"shadow": {"frac": 0.5}}},
            "presets": presets,
            "axes": {"data.shadow.seed": seeds},
            "rules": {"data.shadow.seed": {s: {"train": {"seed": 1000 + s}} for s in seeds}}}


def best_val(results: str, rid: str) -> float:
    m = json.load(open(os.path.join(results, "runs", rid, "metrics.json")))
    # a diverged round stores val_loss as null (non-finite), which never counts as best
    return min((h["val_loss"] for h in m["history"] if h["val_loss"] is not None), default=float("inf"))


def choose_sigma(vals: dict, ref: float) -> float:
    """Largest sigma whose seed-0 best validation loss is at most the reference; else the smallest."""
    ok = [s for s, v in vals.items() if v <= ref]
    return max(ok) if ok else min(vals)


def wn_target(sig: float) -> dict:
    return deep_update(NAT3, {"optim": {"lr": 0.01}, "fl": {"weight_noise": sig}})


def write(grid: dict, out_dir: str) -> str:
    path = os.path.join(out_dir, "configs", "grids", f"{grid['name']}.yaml")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    yaml.safe_dump(grid, open(path, "w"), sort_keys=False)
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("what", choices=["lira", "wn"])
    ap.add_argument("--results", default=os.path.join(ROOT, "results"))
    ap.add_argument("--out", default=ROOT, help="repository root to write configs/grids into")
    a = ap.parse_args()
    if a.what == "lira":
        g = shadow_grid("week07_lira_shadows", shadow_presets(LIRA_TARGETS, a.results),
                        "LiRA shadows for natural3 FedAvg at no DP, epsilon 8, 3, 1 (D45). "
                        "Generated by scripts/make_shadow_grid.py lira.")
        print(write(g, a.out))
        return
    ref = best_val(a.results, REF_EPS8_SEED0)
    vals = {}
    for s in WN_SIGMAS:
        rid = run_id(resolve(deep_update(wn_target(s), {"train": {"seed": 0}})))
        vals[s] = best_val(a.results, rid)
    ok = [s for s in WN_SIGMAS if vals[s] <= ref]
    matched = choose_sigma(vals, ref)
    sigmas = sorted({WN_LITERAL, matched}, reverse=True)
    print("reference eps 8 seed-0 best val loss", round(ref, 4))
    for s in WN_SIGMAS:
        print(f"  weight noise {s:g}: best val loss {vals[s]:.4f}{'  <= ref' if s in ok else ''}")
    print("chosen sigmas", sigmas)
    seeds = {"name": "week07_wn_seeds",
             "note": f"Weight-noise comparator, seeds 1 to 5, sigmas {sigmas} (D45). Generated by "
                     "scripts/make_shadow_grid.py wn.",
             "presets": [wn_target(s) for s in sigmas], "axes": {"train.seed": [1, 2, 3, 4, 5]}}
    print(write(seeds, a.out))
    print(write(shadow_grid("week07_wn_shadows", [wn_target(s) for s in sigmas],
                            f"LiRA shadows for the weight-noise comparator, sigmas {sigmas} (D45)."), a.out))


if __name__ == "__main__":
    main()
